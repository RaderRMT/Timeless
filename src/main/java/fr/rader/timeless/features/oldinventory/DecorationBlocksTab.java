    private void addPaintingVariants(CreativeModeTab.ItemDisplayParameters parameters, CreativeModeTab.Output entries) {
        getOptional(parameters, Registries.PAINTING_VARIANT)
                .ifPresent(
                        wrapper -> CreativeModeTabs.generatePresetPaintings(
                                entries,
                                parameters.holders(),
                                wrapper,
                                variant -> !variant.is(PaintingVariantTags.PLACEABLE),
                                CreativeModeTab.TabVisibility.PARENT_AND_SEARCH_TABS
                        )
                );
    }
